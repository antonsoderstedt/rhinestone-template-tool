/**
 * `npm run quality`: runs the whole artwork matrix and writes docs/QUALITY_REPORT.md. With `--baseline` it also rewrites
 * tests/quality/baseline.json (the numbers the regression test holds the generators to).
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadFixtures, runMatrix, type QualityRow } from '../tests/quality/harness';

const root = path.resolve(__dirname, '..');
const started = Date.now();
const fixtures = loadFixtures();
const rows = runMatrix(fixtures);
const shared = rows.filter((row) => !row.fixture.startsWith('local/'));

if (process.argv.includes('--baseline')) {
  mkdirSync(path.join(root, 'tests/quality'), { recursive: true });
  writeFileSync(path.join(root, 'tests/quality/baseline.json'), JSON.stringify(shared.map((row) => ({ ...row, ms: undefined })), null, 1) + '\n');
}

const pct = (v: number | null) => (v === null ? '–' : `${Math.round(v * 100)}%`);
const imported = new Map<string, string>();
for (const row of rows) if (!imported.has(row.fixture)) imported.set(row.fixture, row.status);

const lines: string[] = [
  '# Artwork quality report',
  '',
  `Generated by \`npm run quality\` (${rows.length} runs in ${((Date.now() - started) / 1000).toFixed(1)} s). Not a hand-edited file.`,
  '',
  'Columns: **cuttable** = no overlap / collision / tight-gap issues; **area** = share of the shape within 0.75 pitch of a stone;',
  '**outline** = share of the outline within one pitch of a stone; **out** = stones outside the shape; **stray** = isolated stones.',
  '',
  '## Import',
  '',
  '| Fixture | Result |',
  '|---|---|',
  ...[...imported].map(([name, status]) => `| ${name} | ${status === 'ok' || status.startsWith('generate') ? 'imports' : status} |`),
  '',
  '## Summary per mode (all imported fixtures)',
  '',
  '| Mode | Runs | Cuttable | Mean area | Mean outline | Out | Stray |',
  '|---|---|---|---|---|---|---|',
];

const okRows = rows.filter((row) => row.status === 'ok');
for (const mode of ['outline', 'fill', 'outline-fill', 'contour'] as const) {
  const group = okRows.filter((row) => row.mode === mode);
  const mean = (pick: (row: QualityRow) => number | null) => {
    const values = group.map(pick).filter((v): v is number => v !== null);
    return values.length ? values.reduce((a, b) => a + b, 0) / values.length : null;
  };
  lines.push(
    `| ${mode} | ${group.length} | ${group.filter((row) => row.notCuttable === 0).length} (${pct(group.filter((row) => row.notCuttable === 0).length / Math.max(group.length, 1))}) | ${pct(mean((r) => r.areaCoverage))} | ${pct(mean((r) => r.outlineCoverage))} | ${group.reduce((n, row) => n + row.outsideStones, 0)} | ${group.reduce((n, row) => n + row.strayStones, 0)} |`,
  );
}

lines.push('', '## Runs that are not cuttable', '', '| Fixture | Width | Stone | Mode | Not cuttable | Stones |', '|---|---|---|---|---|---|');
for (const row of okRows.filter((r) => r.notCuttable > 0).slice(0, 80)) {
  lines.push(`| ${row.fixture} | ${row.widthMm} mm | ${row.stoneSize} | ${row.mode} | ${row.notCuttable} | ${row.stones} |`);
}

writeFileSync(path.join(root, 'docs/QUALITY_REPORT.md'), lines.join('\n') + '\n');
console.log(`Wrote docs/QUALITY_REPORT.md (${rows.length} runs, ${okRows.length} generated).`);
