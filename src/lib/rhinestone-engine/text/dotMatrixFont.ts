/**
 * Returns the dot-matrix glyph for `character`.
 * Falls back to the "?" glyph for any unsupported character.
 *
 * The lookup is case-sensitive. Pass uppercase characters for letters.
 * The text template generator handles uppercasing before calling this.
 */
export function getDotMatrixGlyph(character: string): DotMatrixGlyph {
  return DOT_MATRIX_5X7_FONT[character] ?? DOT_MATRIX_5X7_FONT['?']!;
}
